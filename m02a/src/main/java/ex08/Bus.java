package ex08;

/*
 * ШАГ 2. Автобус: возит 20 посылок, цена рейса — 200 за выезд
 * плюс 5 за каждый километр. Дорогой на коротких заказах,
 * зато на длинных обгоняет такси по цене.
 *
 * Здесь конструктор заполнен неправильно — почини вызов super(...):
 * имя "Автобус", вместимость 20.
 */
public class Bus extends Vehicle {

    public Bus() {
        super("Автобус", 20);
    }

    @Override
    public int tripPrice(int dist) {
        return 200 + 5 * dist;
    }
}
