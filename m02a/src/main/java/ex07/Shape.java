package ex07;

/*
 * Урок 2a.7 — «Абстрактные классы».
 *
 * ГОТОВЫЙ класс — читай, но не меняй. Твоя работа — Rect.java и Circle.java.
 *
 * Shape — «недорисованный чертёж»: фигура «вообще». Какая у неё площадь,
 * зависит от конкретной фигуры, поэтому area() объявлен abstract:
 * тела нет, каждый наследник ОБЯЗАН написать своё.
 * Создать new Shape() нельзя — попробуй, компилятор откажется.
 */
public abstract class Shape {

    // Площадь фигуры. У каждой фигуры считается по-своему.
    public abstract double area();

    // А этот метод общий: написан один раз, но работает для ЛЮБОЙ фигуры,
    // потому что зовёт абстрактный area() — а тот у каждого свой.
    public boolean biggerThan(Shape other) {
        return area() > other.area();
    }
}
