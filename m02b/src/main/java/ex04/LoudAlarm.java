package ex04;

/*
 * Громкая сигнализация должна ПЕРЕОПРЕДЕЛЯТЬ warning()
 * и возвращать "ВНИМАНИЕ!!!".
 *
 * Автор класса был уверен, что переопределил метод, — но тест
 * почему-то получает тихое "Внимание!". Найди ошибку.
 *
 * Подсказка: поставь над методом @Override и прочитай, что скажет
 * компилятор. Именно для этого аннотация и нужна: она просит компилятор
 * ПРОВЕРИТЬ, что метод действительно подменяет метод родителя, а не
 * случайно объявляет новый. Без @Override компилятор молчит — и класс
 * тихо живёт с ДВУМЯ методами вместо одного.
 *
 * Проверка: m02b/src/test/java/ex04/AlarmTest.java (убери @Disabled).
 */
public class LoudAlarm extends Alarm {

    // Выглядит как переопределение. Но так ли это?
    public String warninng() {
        return "ВНИМАНИЕ!!!";
    }
}
